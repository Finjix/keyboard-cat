export interface Key {
  code: number;
  label: string;
  x: number;
  y: number;
  w: number;
  h: number;
}
export const keys: Key[] = [];
const add = (code: number, label: string, x: number, y: number, w = 1, h = 1) =>
  keys.push({ code, label, x, y, w, h });
const row = (
  codes: number[],
  labels: string[],
  y: number,
  start = 0,
  widths: Record<number, number> = {},
) => {
  let x = start;
  codes.forEach((c, i) => {
    const w = widths[i] || 1;
    add(c, labels[i], x, y, w);
    x += w;
  });
};
